@pytest.mark.parametrize(("text", "local_time", "label"), CASES)
def test_proposal_for_phrase(text, local_time, label):
    assert propose_reminder(text, NOW, ZONE) == {"local_time": local_time, "timezone": ZONE, "label": label}


@pytest.mark.parametrize("text", NOTHING)
def test_no_proposal_for_vague_or_past_phrase(text):
    assert propose_reminder(text, NOW, ZONE) is None


def test_case_count():
    assert len(CASES) + len(NOTHING) >= 40


def test_time_zone_changes_local_day():
    # 22:30 in Moscow is already tomorrow in Vladivostok, so "завтра" shifts with the zone.
    late = datetime(2026, 10, 10, 19, 30, tzinfo=UTC)
    assert propose_reminder("завтра в 10", late, "Europe/Moscow")["local_time"] == "2026-10-11T10:00:00"
    assert propose_reminder("завтра в 10", late, "Asia/Vladivostok")["local_time"] == "2026-10-12T10:00:00"


def test_bare_time_that_passed_rolls_to_tomorrow_but_explicit_day_does_not():
    assert propose_reminder("в 9", NOW, ZONE)["local_time"] == "2026-10-11T09:00:00"
    assert propose_reminder("сегодня в 9", NOW, ZONE) is None


def test_weekday_is_never_today():
    friday = datetime(2026, 10, 9, 5, 0, tzinfo=UTC)
    assert propose_reminder("в пятницу", friday, ZONE)["local_time"] == "2026-10-16T09:00:00"


def test_wall_time_inside_dst_gap_is_not_proposed():
    # New York skips 02:00-03:00 on 2027-03-14.
    now = datetime(2027, 3, 10, 15, 0, tzinfo=UTC)
    assert propose_reminder("14.03 в 2:30", now, "America/New_York") is None
    assert propose_reminder("14.03 в 3:30", now, "America/New_York")["local_time"] == "2027-03-14T03:30:00"


def test_naive_now_is_treated_as_utc_and_parser_is_pure():
    assert propose_reminder("завтра", NOW.replace(tzinfo=None), ZONE)["local_time"] == "2026-10-11T09:00:00"
    assert parse_due_text("завтра в 10", datetime(2026, 10, 10, 15, 0)) == datetime(2026, 10, 11, 10, 0)


def test_label_uses_year_only_when_it_differs():
    now = datetime(2026, 10, 10, 15, 0)
    assert label_for(datetime(2026, 12, 1, 9, 0), now) == "1 декабря в 09:00"
    assert label_for(datetime(2027, 1, 5, 9, 0), now) == "5 января 2027 в 09:00"
